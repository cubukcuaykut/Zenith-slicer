def _rolling_forecast(series: np.ndarray, fc: TrafficForecaster,
                      slice_name: str) -> np.ndarray:
    """Build an aligned one-step-ahead forecast series for DQN training."""
    w = fc.window
    out = np.empty_like(series)
    for t in range(len(series)):
        if t < w:
            out[t] = series[t]
        else:
            out[t] = fc.predict(slice_name, series[t - w:t])
    return out


