# ----------------------------------------------------------------------
# Scalability analysis (control overhead vs. number of slices)
# ----------------------------------------------------------------------
def run_scalability(agent: DQNAgent, fc: TrafficForecaster,
                    clf: SLAViolationClassifier) -> None:
    """
    Measure ZENITH closed-loop control overhead as the number of concurrently
    orchestrated slices grows. Each control cycle performs, per slice:
      LSTM forecast + DQN action selection + SLA-violation classification.
    The total per-cycle inference latency therefore scales linearly O(N) in
    the number of slices N, which we verify empirically by timing.
    """
    from .dqn_agent import slice_bounds, clip
    from .network_model import Allocation

    counts = [3, 6, 12, 24, 48, 96]
    per_cycle_ms: List[float] = []
    reps = 30

    for n in counts:
        slist = [C.SLICES[i % len(C.SLICES)] for i in range(n)]
        hists = [np.full(fc.window, C.TRAFFIC[s].base, dtype=np.float32)
                 for s in slist]
        allocs = []
        for s in slist:
            b = slice_bounds(s)
            spec = C.SLICE_SPECS[s]
            base = b["base"]
            allocs.append(Allocation(
                n_prb={s: base / spec.mbps_per_prb},
                b_transport={s: base}, c_upf={s: base}))

        # Warmup (exclude JIT / lazy-init cost).
        for i, s in enumerate(slist):
            f = fc.predict(s, hists[i])
            st = np.zeros(7, dtype=np.float32)
            agent.act(st, greedy=True)
            kpi = nm.evaluate_slice(s, f, allocs[i])
            clf.predict_proba(kpi)

        t0 = time.perf_counter()
        for _ in range(reps):
            for i, s in enumerate(slist):
                spec = C.SLICE_SPECS[s]
                b = slice_bounds(s)
                f = fc.predict(s, hists[i])
                kpi = nm.evaluate_slice(s, f, allocs[i])
                st = np.array([
                    allocs[i].n_prb[s] / b["prb_max"],
                    allocs[i].b_transport[s] / b["tx_max"],
                    allocs[i].c_upf[s] / b["core_max"],
                    min(kpi.l_e2e / spec.l_max_ms, 3.0),
                    f / (b["base"] * 3.0),
                    spec.l_max_ms / 50.0,
                    spec.mbps_per_prb / 1.5,
                ], dtype=np.float32)
                agent.act(st, greedy=True)
                clf.predict_proba(kpi)
        dt_ms = (time.perf_counter() - t0) / reps * 1000.0
        per_cycle_ms.append(dt_ms)

    # Plot.
    plt.figure(figsize=(7, 4.2))
    plt.plot(counts, per_cycle_ms, "o-", color="#1f77b4", lw=2,
             label="Measured per-cycle inference")
    # Ideal linear reference anchored at first point.
    ideal = [per_cycle_ms[0] * (c / counts[0]) for c in counts]
    plt.plot(counts, ideal, "--", color="#d62728", alpha=0.7,
             label="Ideal linear $O(N)$")
    plt.xlabel("Number of concurrent slices $N$")
    plt.ylabel("Control-loop inference time (ms)")
    plt.title("ZENITH Closed-Loop Control Overhead vs. Slice Count")
    plt.legend()
    plt.grid(alpha=0.3)
    plt.tight_layout()
    p = os.path.join(RESULTS_DIR, "fig_scalability.png")
    plt.savefig(p, dpi=150)
    plt.close()
    print(f"[saved] figure -> {p}")

    # Console + CSV summary.
    print("\n--- SCALABILITY (control overhead) ---")
    for c, m in zip(counts, per_cycle_ms):
        print(f"  N={c:>3} slices : {m:7.3f} ms/cycle "
              f"({m / c:6.4f} ms/slice)")
    with open(os.path.join(RESULTS_DIR, "scalability.csv"), "w",
              encoding="utf-8") as fcsv:
        fcsv.write("n_slices,per_cycle_ms,per_slice_ms\n")
        for c, m in zip(counts, per_cycle_ms):
            fcsv.write(f"{c},{m:.4f},{m / c:.6f}\n")


# ----------------------------------------------------------------------
# Main
# ----------------------------------------------------------------------
def main() -> None:
    t0 = time.time()
    seed_everything(C.SEED)
    os.makedirs(RESULTS_DIR, exist_ok=True)

    print("[1/5] Generating training traffic ...")
    gen = TrafficGenerator(seed=C.SEED)
    train_series = gen.generate_series(C.LSTM_CFG.train_steps)

    print("[2/5] Training LSTM traffic forecaster ...")
    fc = TrafficForecaster()
    mape = fc.train(train_series)
    print("       MAPE (%):", {k: round(v, 2) for k, v in mape.items()})

    print("[3/5] Training SLA-violation classifier ...")
    clf = SLAViolationClassifier()
    clf_metrics = clf.train(seed=C.SEED)
    print("       metrics:", {k: round(v, 3) for k, v in clf_metrics.items()})

    print("[4/5] Training DQN cross-domain optimizer ...")
    forecast_series = {s: _rolling_forecast(train_series[s], fc, s) for s in C.SLICES}
    envs = [SliceTrainEnv(s, train_series[s], forecast_series[s], seed=C.SEED + i)
            for i, s in enumerate(C.SLICES)]
    agent = DQNAgent()
    dqn_returns = agent.train(envs)
    print(f"       final 10-ep mean return: {np.mean(dqn_returns[-10:]):.2f}")

    print("[5/5] Evaluating schemes on held-out trace ...")
    eval_gen = TrafficGenerator(seed=C.SEED + 1000)
    eval_series = eval_gen.generate_series(C.EVAL_CFG.eval_steps)

    results: Dict[str, SchemeResult] = {}
    for sch in C.SCHEMES:
        ctrl = build_controller(sch, agent=agent, forecaster=fc, sla_clf=clf)
        results[sch] = run_scheme(ctrl, eval_series)

    print_kpi_tables(results, mape, clf_metrics)
    write_latex_tables(results, mape, clf_metrics)
    write_csv(results)
    make_figures(results, dqn_returns, train_series, fc)
    make_advanced_figures(results)
    run_scalability(agent, fc, clf)

    print(f"\nDone in {time.time() - t0:.1f}s. Artifacts in: {RESULTS_DIR}")


if __name__ == "__main__":
    main()
